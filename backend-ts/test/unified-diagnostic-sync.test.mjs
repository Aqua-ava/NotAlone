 const f=await fixture(t,{registryModule:new URL('./fixtures/history/continuity-diagnostic-registry.mjs',import.meta.url).href});
 const log=configureDiagnosticLog(f.root,{proc:'backend',development:true});t.after(()=>log.close());
 f.state.pageRecords=[record('shard-a','1')];f.channel.guardSession={loss:new Promise(()=>{})};
