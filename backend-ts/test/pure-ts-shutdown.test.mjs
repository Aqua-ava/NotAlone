import test from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {pureTsFixture} from './pure-ts-runtime-fixture.mjs';
import {syntheticProvider} from './pure-ts-provider-fixture.mjs';
test('纯 TS 公开关闭取消在途供应商并排空，没有晚候选或遗留进程',{timeout:20000},async t=>{
 const f=await pureTsFixture(t),owner=randomUUID(),contact=randomUUID(),binding=randomUUID();
 await f.client.query("INSERT INTO owner(id,display_name)VALUES($1,'合成本人')",[owner]);
 await f.client.query("INSERT INTO contact(id,owner_id,display_name)VALUES($1,$2,'合成联系人')",[contact,owner]);
 await f.client.query("INSERT INTO conversation_binding(id,owner_id,contact_id,channel,account_scope,conversation_locator)VALUES($1,$2,$3,'wechat','synthetic','friend-a')",[binding,owner,contact]);
 let entered,closed;const began=new Promise(resolve=>entered=resolve),providerClosed=new Promise(resolve=>closed=resolve);
 const provider=await syntheticProvider(t,async(_body,res)=>{res.once('close',closed);entered();});
 const environment={NOTALONE_OWNER_ID:owner,NOTALONE_DEEPSEEK_API_KEY:'synthetic-only',NOTALONE_SYNTHETIC_PROVIDER_URL:provider.url};
 const app=await f.start(environment),request={contact_id:contact,idempotency_key:randomUUID(),content:{type:'rewrite_draft',draft_text:'稍后联系',include_relationship_context:false},skill_disabled:true};
 const inFlight=app.request('/api/reply/generate',request);
 await Promise.race([began,inFlight.then(result=>{throw new Error('供应商开始前意外终态：'+result.status);})]);
 const shutdown=await app.request('/api/runtime/shutdown',{});assert.equal(shutdown.data.state,'stopped');
 const stopped=await inFlight;assert.equal(stopped.status,409);assert.equal(stopped.data.error,'reply_cancelled');
 await providerClosed;assert.equal(await app.host.waitForExit(7000),true);assert.equal(provider.requests.length,1);
 assert.throws(()=>process.kill(app.host.pid,0));
 const restarted=await f.start(environment);
 assert.equal((await restarted.request('/api/contacts')).data.contacts[0].contact_id,contact);assert.equal(provider.requests.length,1,'重开仅恢复业务状态，不重放已取消旧调用');
 await restarted.request('/api/runtime/shutdown',{});assert.equal(await restarted.host.waitForExit(7000),true);
});
