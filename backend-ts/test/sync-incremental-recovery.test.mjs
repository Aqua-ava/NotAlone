import test from 'node:test';
import assert from 'node:assert/strict';
import {HostStorage} from '../src/host-storage.ts';
import {SyncScopeService} from '../src/sync-scope.ts';
import {SyncIncrementalStore} from '../src/sync-incremental-store.ts';
import {SyncIncrementalRecovery} from '../src/sync-incremental-recovery.ts';
import {createStorageFixture} from './host-storage-fixture.mjs';

test('恢复保留进行中计数，完成后显式新检查重置，关闭拒绝继续',async t=>{
  const f=await createStorageFixture();t.after(()=>f.close());
  const storage=await HostStorage.open(f.options);t.after(()=>storage.close());
  const {owner_id:ownerId}=await storage.initializeOwner('合成用户');
  await f.client.query("INSERT INTO owner_channel_identity(owner_id,channel,external_id,observed_name) VALUES($1,'wechat','synthetic-account','合成账号')",[ownerId]);
  const scope=new SyncScopeService({storage,ownerId,accountScope:'synthetic-account'});
  await scope.setMode({mode:'all_private',confirmed:true});
  await f.client.query('INSERT INTO front_sync_state(owner_id,enabled,enabled_at) VALUES($1,true,now())',[ownerId]);
  await scope.enroll([{username:'friend-a',display_name:'合成联系人',chat_type:'private'}]);
  const store=new SyncIncrementalStore({storage,ownerId,accountScope:'synthetic-account'});
  const binding=(await store.listBindings())[0];
  const recovery=new SyncIncrementalRecovery({store,storage,ownerId});
  let state=await recovery.prepare(binding,{triggerAt:new Date('2026-10-24T01:00:00Z')});
  assert.equal(state.phase,'backfilling');
  state=await recovery.progress(binding,{previous:state,messageCount:2,nonTextCount:1,lastLocalId:'12',lastCursor:'cursor-12',hasMore:true});
  const restarted=new SyncIncrementalRecovery({store,storage,ownerId});
  state=await restarted.prepare(binding,{triggerAt:new Date('2026-10-24T02:00:00Z')});
  assert.equal(state.message_count,2);
  assert.equal(state.trigger_at,'2026-10-24T01:00:00.000Z');
  state=await restarted.progress(binding,{previous:state,messageCount:1,nonTextCount:0,lastLocalId:'9',lastCursor:'cursor-9',hasMore:false});
  assert.equal(state.phase,'complete');assert.equal(state.message_count,3);
  state=await restarted.prepare(binding,{triggerAt:new Date('2026-10-24T03:00:00Z')});
  assert.equal(state.message_count,0);
  await store.setEnabled(false);
  await assert.rejects(restarted.progress(binding,{previous:state,messageCount:1,nonTextCount:0,lastLocalId:'13',lastCursor:'cursor-13',hasMore:false}));
});
